/**
 * Standalone process runner executed with USE_LEGACY_BCRYPT=true
 * to verify pure bcryptjs rollback behavior in an isolated Node process.
 *
 * NOTE: Changing USE_LEGACY_BCRYPT requires a process/container restart
 * because password.ts evaluates the flag at module evaluation time.
 */
import * as nativeBcrypt from '@node-rs/bcrypt';
import bcryptjs from 'bcryptjs';
import { hashPin, verifyPin, SALT_ROUNDS } from './password';

export async function runRollbackVerification() {
  const isLegacyActive = process.env.USE_LEGACY_BCRYPT === 'true';
  if (!isLegacyActive) {
    throw new Error('USE_LEGACY_BCRYPT must be set to "true" in this process');
  }

  const PIN = 'rollback-driver-5566';
  const WRONG_PIN = 'wrong-pin-9999';

  // 1. Hash with rollback engine (bcryptjs)
  const rollbackHash = await hashPin(PIN);
  if (!rollbackHash.startsWith('$2b$12$') && !rollbackHash.startsWith('$2a$12$')) {
    throw new Error(`Unexpected hash format from rollback engine: ${rollbackHash}`);
  }

  // 2. Verify with rollback engine (bcryptjs)
  const verifyRollbackSelf = await verifyPin(PIN, rollbackHash);
  if (!verifyRollbackSelf) {
    throw new Error('Rollback verifyPin failed to verify its own hash');
  }
  const verifyRollbackWrong = await verifyPin(WRONG_PIN, rollbackHash);
  if (verifyRollbackWrong) {
    throw new Error('Rollback verifyPin incorrectly accepted a wrong PIN');
  }

  // 3. Directly verify rollbackHash using bcryptjs directly
  const bcryptjsDirectVerify = await bcryptjs.compare(PIN, rollbackHash);
  if (!bcryptjsDirectVerify) {
    throw new Error('bcryptjs direct compare failed on rollbackHash');
  }

  // 4. Cross-engine check: native @node-rs/bcrypt verifies rollback hash
  const nativeVerifiesRollback = await nativeBcrypt.verify(PIN, rollbackHash);
  if (!nativeVerifiesRollback) {
    throw new Error('native @node-rs/bcrypt failed to verify hash generated by rollback engine');
  }

  // 5. Cross-engine check: rollback verifyPin verifies hash created by native @node-rs/bcrypt
  const nativeCreatedHash = await nativeBcrypt.hash(PIN, { cost: 12 });
  const rollbackVerifiesNative = await verifyPin(PIN, nativeCreatedHash);
  if (!rollbackVerifiesNative) {
    throw new Error('Rollback verifyPin failed to verify hash created by native @node-rs/bcrypt');
  }
  const rollbackRejectsWrongOnNative = await verifyPin(WRONG_PIN, nativeCreatedHash);
  if (rollbackRejectsWrongOnNative) {
    throw new Error('Rollback verifyPin accepted wrong PIN on native hash');
  }

  // 6. Verify legacy $2a$ format hash in rollback mode
  const salt2a = bcryptjs.genSaltSync(10).replace('$2b$', '$2a$');
  const legacy2aHash = await bcryptjs.hash(PIN, salt2a);
  const rollbackVerifies2a = await verifyPin(PIN, legacy2aHash);
  if (!rollbackVerifies2a) {
    throw new Error('Rollback verifyPin failed on $2a$ hash');
  }

  return {
    success: true,
    isLegacyActive,
    saltRounds: SALT_ROUNDS,
    rollbackHashPrefix: rollbackHash.slice(0, 7),
    nativeCreatedHashPrefix: nativeCreatedHash.slice(0, 7),
    rollbackSelfVerify: verifyRollbackSelf,
    nativeVerifiesRollback,
    rollbackVerifiesNative,
    rollbackVerifies2a,
  };
}

import { fileURLToPath } from 'node:url';
import path from 'node:path';

const currentFile = fileURLToPath(import.meta.url);
const entryFile = process.argv[1] ? path.resolve(process.argv[1]) : '';

if (entryFile && path.resolve(currentFile) === entryFile) {
  runRollbackVerification()
    .then((result) => {
      console.log(JSON.stringify(result));
      process.exit(0);
    })
    .catch((err) => {
      console.error(err.message || String(err));
      process.exit(1);
    });
}
